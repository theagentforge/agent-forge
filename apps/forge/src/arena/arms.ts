import { trapCardText } from "@forge/shared";
import modelLines from "../../../../lab/003-trap-cards/prompts/D-model-lines.json";

// Forge Lab #3 arms (lab/003-trap-cards/PREREGISTRATION.md). The text is appended to the harness system prompt for a
// whole event, the way a user's custom instructions are. The arm texts are published in the lab folder; tests check
// that these match them exactly.

export type Arm = "none" | "placebo" | "card" | "model";
export const ARMS: Arm[] = ["none", "placebo", "card", "model"];

/** Arm B: same length as the card, no checks in it. Identical to lab/003-trap-cards/prompts/B-placebo.txt. */
export const PLACEBO_TEXT = `Notes on how I like answers from my AI assistant (style card v1.0, 2026-10-15):
- Write in plain, friendly English. Short sentences are better than long ones, and everyday words beat jargon.
- When you list things, use simple bullet points and keep each bullet to one idea so it is easy to scan.
- Put the most useful part of the answer first, then any background I might want to read afterwards.
- Use numbers as digits, and write dates as day, month and year so they are never ambiguous to me.
- If an answer needs a heading, keep it to a few words. Avoid bold text in the middle of sentences.
- Keep a calm, even tone. There is no need for exclamation marks, emojis or very enthusiastic language.
- When you mention a time, say which time zone it is in, and use the 24-hour clock where it is clearer.
- End with a one-line summary when an answer runs longer than a few short paragraphs, so I can skim it.`;

/** Arm D lines per model, generated by the pre-registered rule and frozen in the lab folder before Lab #3 runs. */
const MODEL_LINES = modelLines as Record<string, string[]>;

/** The text appended to the system prompt for an arm (null: nothing appended). */
export function armText(arm: Arm | null | undefined, modelId: string): string | null {
  if (!arm || arm === "none") return null;
  if (arm === "placebo") return PLACEBO_TEXT;
  const card = trapCardText();
  if (arm === "card") return card;
  const lines = MODEL_LINES[modelId] ?? [];
  return lines.length ? `${card}\n${lines.map((l) => `- ${l}`).join("\n")}` : card;
}
