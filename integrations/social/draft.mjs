// The daily social drafter and its separate verifier (docs/launch/social-strategy.md §9.1–§9.3, ADR 0010 §2).
//
//   node draft.mjs draft  <site>   files today's posts (US Eastern date) as issues labelled post, auto, type:<slug>
//   node draft.mjs verify <site>   re-checks every open draft against public pages and labels it verified, or says why not
//
// The drafter takes the Worker's drafts (/api/v1/social/drafts: live data, fixed templates, several wordings each) and
// applies the guards: a variety guard (no opening line repeated within 14 days, X's duplicate rule), a no-URL guard
// (main posts carry no link; at most one link reply a day) and the hold window (posts go out 3+ hours after filing).
// The verifier is separate code that trusts nothing in the issue: it re-fetches each bout's refereed result, checks that
// every number in the text is a recorded fact, re-fetches the drafts to confirm the data hasn't changed, and fails
// closed. Posting stays with post-to-x.mjs: a draft only goes out with the verified label, and new types need approve.

import { DRAFT_MARK, HOLD_WINDOW_MS, parsePosts, validatePosts, weightedLength } from "./post-to-x.mjs";

export { DRAFT_MARK };
export const VARIETY_DAYS = 14;
export const OPENING_CHARS = 60;
/** Same-author posts within this of each other lose reach (X halves the second in a feed, §2): keep them apart. */
export const SPACING_MS = 3 * 3_600_000;
const URL_RE = /https?:\/\/\S+/g;

/** The US Eastern date (YYYY-MM-DD) of a moment. */
export function easternDate(ms) {
  return new Intl.DateTimeFormat("en-CA", { timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(ms));
}

/** A post's opening, normalised, for the duplicate rule. */
export const opening = (text) => text.toLowerCase().replace(/\s+/g, " ").trim().slice(0, OPENING_CHARS);

/** Adds ?from=x-<type> to our own links that have no from tag (§9.8), so the Ops Digest counts the click-ins. */
export function tagLinks(text, type) {
  return text.replace(/https:\/\/theagentforge\.io(\/[^\s?#]*)?(\?[^\s#]*)?/g, (m, path = "", query = "") =>
    /[?&]from=/.test(query) ? m : `https://theagentforge.io${path}${query ? `${query}&` : "?"}from=x-${type}`,
  );
}

/**
 * Picks the first wording whose opening hasn't been used in the last 14 days and that fits X's limit. Main posts never
 * carry a URL (it's stripped), and the link reply is dropped if today already has one. Returns null if nothing fits.
 */
export function chooseDraft(draft, { recentOpenings, linkReplyToday }) {
  for (const raw of draft.texts) {
    const text = raw.replace(URL_RE, "").replace(/[ \t]+\n/g, "\n").trim();
    if (!text || weightedLength(text) > 280) continue;
    if (recentOpenings.has(opening(text))) continue;
    const reply = draft.reply && !linkReplyToday ? tagLinks(draft.reply, draft.type) : null;
    return { text, reply };
  }
  return null;
}

/** The issue body for one draft: the post block (and its reply), and the facts the verifier re-checks. */
export function draftBody(draft, chosen, date, swap = null) {
  const lines = [chosen.text];
  if (draft.image) lines.push(`image: ${draft.image}`);
  if (draft.alt) lines.push(`alt: ${draft.alt.replace(/\s+/g, " ").slice(0, 1000)}`);
  if (draft.video) lines.push(`video: ${draft.video}`);
  if (draft.poll) lines.push(`poll: ${draft.poll.options.join(" | ")} (${draft.poll.duration_minutes} min)`);
  const at = draft.at.slice(0, 16) + "Z";
  const blocks = [`\`\`\`post ${at}\n${lines.join("\n")}\n\`\`\``];
  if (chosen.reply) blocks.push(`\`\`\`post ${at} reply\n${chosen.reply}\n\`\`\``);
  const mark = JSON.stringify({ type: draft.type, date, at: draft.at, ...(swap ? { swap } : {}), facts: draft.facts });
  return [
    `**Auto-drafted ${draft.type}** for ${date} (US Eastern), from live data (social strategy §6, ADR 0010).`,
    "It posts by itself at the time below once the verifier labels it `verified`, unless you comment `hold`. The first post of each type waits for your `approve`.",
    "",
    ...blocks,
    "",
    `<!-- forge-draft ${mark} -->`,
    "",
    "---",
    "_Generated by [Claude Code](https://claude.ai/code)_",
  ].join("\n");
}

function github(env, fetcher) {
  const repo = env.GITHUB_REPOSITORY;
  if (!repo || !env.GH_TOKEN) throw new Error("GITHUB_REPOSITORY and GH_TOKEN are required");
  return async (method, path, body) => {
    const res = await fetcher(`https://api.github.com/repos/${repo}${path}`, {
      method,
      headers: { Authorization: `Bearer ${env.GH_TOKEN}`, Accept: "application/vnd.github+json", "Content-Type": "application/json", "User-Agent": "forge-social-draft" },
      body: body ? JSON.stringify(body) : undefined,
    });
    if (!res.ok) throw new Error(`GitHub ${method} ${path}: HTTP ${res.status}`);
    return res.status === 204 ? null : res.json();
  };
}

/** Recent post issues (14 days), for the variety guard, the link-reply cap and de-duplication. */
async function recentPostIssues(gh, now) {
  const since = new Date(now - VARIETY_DAYS * 86_400_000).toISOString();
  const out = [];
  for (let page = 1; page <= 5; page++) {
    const rows = await gh("GET", `/issues?labels=post&state=all&since=${since}&per_page=100&page=${page}`);
    out.push(...rows.filter((r) => !r.pull_request));
    if (rows.length < 100) break;
  }
  return out;
}

/** The weekly learning report's slot move (§9.9), as written by the Monday Ops Digest. */
export const MIX_MARK = /<!-- forge-mix (\{[^}]*\}) -->/;

/** "from,to" if the latest digest moved a slot for the week (Mon–Sun) holding `date`, else null. */
export function swapFromDigests(issues, date) {
  for (const it of [...(Array.isArray(issues) ? issues : [])].sort((a, b) => Date.parse(b.created_at ?? 0) - Date.parse(a.created_at ?? 0))) {
    const m = MIX_MARK.exec(it.body ?? "");
    if (!m) continue;
    try {
      const mix = JSON.parse(m[1]);
      const days = (Date.parse(`${date}T12:00:00Z`) - Date.parse(`${mix.week}T12:00:00Z`)) / 86_400_000;
      if (!(days >= 0 && days < 7)) return null;
      return /^[a-z-]+$/.test(mix.from ?? "") && /^[a-z-]+$/.test(mix.to ?? "") ? `${mix.from},${mix.to}` : null;
    } catch {
      return null;
    }
  }
  return null;
}

/** Files today's drafts. Never files the same type and date twice. */
export async function draft(site, env = process.env, fetcher = fetch, now = Date.now()) {
  const gh = github(env, fetcher);
  const date = easternDate(now);
  const swap = swapFromDigests(await gh("GET", "/issues?labels=ops-digest&state=all&per_page=10").catch(() => []), date);
  const res = await fetcher(`${site}/api/v1/social/drafts?date=${date}${swap ? `&swap=${swap}` : ""}`, { headers: { Accept: "application/json" } });
  if (!res.ok) throw new Error(`drafts: HTTP ${res.status}`);
  const { drafts = [] } = await res.json();
  const issues = await recentPostIssues(gh, now);
  const recentOpenings = new Set();
  let linkReplyToday = false;
  const filed = new Set();
  /** Times of posts still to go out on open post issues (approved or not), so a draft never lands within 3 hours. */
  const taken = [];
  for (const it of issues) {
    let posts = [];
    try {
      posts = parsePosts(it.body ?? "");
    } catch {}
    if (it.state === "open") for (const p of posts) if (!p.reply && p.at) taken.push(p.at);
    for (const p of posts) {
      if (!p.reply) recentOpenings.add(opening(p.text));
      if (p.reply && URL_RE.test(p.text) && p.at && easternDate(p.at) === date) linkReplyToday = true;
      URL_RE.lastIndex = 0;
    }
    const m = DRAFT_MARK.exec(it.body ?? "");
    if (m) {
      try {
        const k = JSON.parse(m[1]);
        filed.add(`${k.type}|${k.date}`);
      } catch {}
    }
  }
  const log = [];
  for (const d of drafts) {
    if (filed.has(`${d.type}|${date}`)) {
      log.push(`${d.type}: already filed`);
      continue;
    }
    if (Date.parse(d.at) < now + HOLD_WINDOW_MS) {
      log.push(`${d.type}: too late for the 3-hour hold window`);
      continue;
    }
    const at = Date.parse(d.at);
    if (taken.some((x) => Math.abs(x - at) < SPACING_MS)) {
      log.push(`${d.type}: another post is within 3 hours of ${d.at}; skipped`);
      continue;
    }
    const chosen = chooseDraft(d, { recentOpenings, linkReplyToday });
    if (!chosen) {
      log.push(`${d.type}: every wording repeats a recent opening or is too long; skipped`);
      continue;
    }
    const body = draftBody(d, chosen, date, swap);
    validatePosts(parsePosts(body));
    await gh("POST", `/issues`, { title: `X auto: ${d.type} (${date})`, body, labels: ["post", "auto", `type:${d.type}`] });
    recentOpenings.add(opening(chosen.text));
    taken.push(at);
    if (chosen.reply) linkReplyToday = true;
    log.push(`${d.type}: filed for ${d.at}`);
  }
  return log;
}

/** Words and claims the brand and the law rule out (§1, §5): insults, "malicious", safety promises. */
export const BANNED = /\b(dumb|stupid|idiot\w*|trash|garbage|slop|glazing|clanker|malicious|protects?|guarantee\w*|100% safe|safe from)\b/i;

/** Text minus model names, job titles, dates and times, so only the claimed numbers are left to check. */
export function claimedNumbers(text, names) {
  let t = text;
  for (const n of [...names].sort((a, b) => b.length - a.length)) t = t.split(n).join(" ");
  t = t.replace(/\b\d{1,2} (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, " ").replace(/\b\d{1,2}(:\d{2})? ?(am|pm) ET\b/gi, " ").replace(/Lab #\d+/g, " ");
  return (t.match(/\d[\d,]*(\.\d+)?/g) ?? []).map((s) => Number(s.replace(/,/g, "")));
}

/**
 * Verifies one draft issue. Every check must pass (fails closed):
 * 1. the main post has no URL and no banned words; 2. each bout named in the facts is re-read from its public refereed
 * result (/arena/run/<id>.json) and matches (model, fell, passed); 3. every number in the text is a recorded fact; 4. the
 * Worker still drafts the same wording from today's data.
 */
export async function verifyIssue(issue, site, fetcher = fetch) {
  const m = DRAFT_MARK.exec(issue.body ?? "");
  if (!m) return { ok: false, why: ["no forge-draft facts"] };
  const mark = JSON.parse(m[1]);
  const posts = parsePosts(issue.body);
  validatePosts(posts);
  const main = posts.find((p) => !p.reply);
  const why = [];
  if (!main) return { ok: false, why: ["no main post"] };
  if (/https?:\/\//.test(main.text)) why.push("the main post has a URL");
  if (BANNED.test(main.text)) why.push(`banned wording: "${BANNED.exec(main.text)[0]}"`);
  const names = new Set();
  for (const r of mark.facts?.runs ?? []) {
    const res = await fetcher(`${site}/arena/run/${encodeURIComponent(r.id)}.json`, { headers: { Accept: "application/json" } });
    if (!res.ok) {
      why.push(`bout ${r.id.slice(0, 8)}: HTTP ${res.status}`);
      continue;
    }
    const run = await res.json();
    const fell = (run.result?.traps ?? []).some((t) => t.triggered);
    if (run.model !== r.model) why.push(`bout ${r.id.slice(0, 8)}: model is ${run.model}, not ${r.model}`);
    if (fell !== r.fell) why.push(`bout ${r.id.slice(0, 8)}: fell is ${fell}, the draft says ${r.fell}`);
    if (Boolean(run.result?.passed) !== r.passed) why.push(`bout ${r.id.slice(0, 8)}: passed is ${Boolean(run.result?.passed)}`);
  }
  const swapQ = typeof mark.swap === "string" && /^[a-z-]+,[a-z-]+$/.test(mark.swap) ? `&swap=${mark.swap}` : "";
  const res = await fetcher(`${site}/api/v1/social/drafts?date=${mark.date}${swapQ}`, { headers: { Accept: "application/json" } });
  const now = res.ok ? await res.json() : null;
  const same = now?.drafts?.find((d) => d.type === mark.type);
  if (!same) why.push("the Worker no longer drafts this post from today's data");
  else if (!same.texts.some((t) => t.replace(/https?:\/\/\S+/g, "").replace(/[ \t]+\n/g, "\n").trim() === main.text)) why.push("the data changed since drafting: the wording no longer matches");
  // Names that may carry digits (Claude Sonnet 5.5, GPT-6.1 Sol), from the drafts' own facts and the bouts.
  for (const d of now?.drafts ?? []) for (const n of d.facts?.names ?? []) names.add(n);
  for (const n of mark.facts?.names ?? []) names.add(n);
  const allowed = new Set([...(mark.facts?.numbers ?? []), ...(same?.facts?.numbers ?? [])]);
  const stray = claimedNumbers(main.text, names).filter((n) => !allowed.has(n));
  if (stray.length) why.push(`numbers not in the recorded facts: ${stray.join(", ")}`);
  return { ok: why.length === 0, why };
}

/** Verifies every open draft that isn't verified, held or already explained. */
export async function verify(site, env = process.env, fetcher = fetch) {
  const gh = github(env, fetcher);
  const open = await gh("GET", `/issues?labels=post,auto&state=open&per_page=100`);
  const log = [];
  for (const it of open) {
    const labels = new Set(it.labels.map((l) => l.name));
    if (labels.has("verified") || labels.has("held") || !DRAFT_MARK.test(it.body ?? "")) continue;
    let result;
    try {
      result = await verifyIssue(it, site, fetcher);
    } catch (e) {
      result = { ok: false, why: [String(e?.message ?? e)] };
    }
    if (result.ok) {
      await gh("POST", `/issues/${it.number}/labels`, { labels: ["verified"] });
      await gh("POST", `/issues/${it.number}/comments`, { body: "Verified: every bout re-read from its refereed result, every number is a recorded fact, and today's data gives the same wording. (ADR 0010)" });
      log.push(`#${it.number}: verified`);
    } else {
      await gh("POST", `/issues/${it.number}/comments`, { body: `Not verified, so it won't post:\n${result.why.map((w) => `- ${w}`).join("\n")}\n\nThe drafter files a fresh draft tomorrow if the data allows.` });
      await gh("PATCH", `/issues/${it.number}`, { state: "closed", state_reason: "not_planned" });
      log.push(`#${it.number}: not verified (${result.why.join("; ")})`);
    }
  }
  return log;
}

const [cmd, siteArg] = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  const site = (siteArg || "https://theagentforge.io").replace(/\/$/, "");
  if (!/^https:\/\/[a-z0-9.-]+$/.test(site)) throw new Error("site must be https://<host>");
  const log = cmd === "draft" ? await draft(site) : cmd === "verify" ? await verify(site) : (() => { throw new Error("usage: node draft.mjs draft|verify <site>"); })();
  console.log(log.join("\n") || "nothing to do");
}
