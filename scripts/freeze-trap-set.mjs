#!/usr/bin/env node
// Freeze a Trap Set version (B3-05, ADR 0101): write apps/forge/src/seed/benchmark/v<version>.json.txt and regenerate the
// snapshot registry (apps/forge/src/seed/benchmark/index.ts, with each file's sha256). A frozen snapshot is never
// changed: this script refuses if the file exists, and test/benchmark-versions.test.ts fails if its bytes change.
//
//   node scripts/freeze-trap-set.mjs --version 1.1
//       Builds the current version's definition (trapSetDefinition() in apps/forge/src/arena/benchmark-versions.ts)
//       inside the Workers test runtime and writes it as a "frozen" snapshot from the current commit. --version must
//       equal the current version (TRAP_SET.version), or it refuses. Commit first, so the recorded commit is the code.
//   node scripts/freeze-trap-set.mjs --version 1.0 --from-definition <file.json> --kind reconstructed --commit <sha>
//       Writes a "reconstructed" snapshot from a definition built at an older commit (how 1.0 was made on 29 Oct).
//   node scripts/freeze-trap-set.mjs --index
//       Only regenerates index.ts from the files present (for example after a rebase).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const app = join(root, "apps/forge");
const dir = join(app, "src/seed/benchmark");
const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const die = (msg) => {
  console.error(msg);
  process.exit(1);
};
const byVersion = (a, b) => a.localeCompare(b, "en", { numeric: true });

/** The sha256 already recorded in index.ts for each version (a frozen snapshot's hash is never changed). */
function recordedShas() {
  const p = join(dir, "index.ts");
  if (!existsSync(p)) return new Map();
  return new Map([...readFileSync(p, "utf8").matchAll(/version: "([^"]+)", sha256: "([0-9a-f]{64})"/g)].map((m) => [m[1], m[2]]));
}

function writeIndex() {
  const files = readdirSync(dir).filter((f) => /^v\d+\.\d+(\.\d+)?\.json\.txt$/.test(f));
  const versions = files.map((f) => f.slice(1, -".json.txt".length)).sort(byVersion);
  const id = (v) => `v${v.replace(/\./g, "_")}`;
  const before = recordedShas();
  const lines = versions.map((v) => {
    const sha = createHash("sha256").update(readFileSync(join(dir, `v${v}.json.txt`))).digest("hex");
    // Review (ADR 0105): re-indexing must not bless an edited snapshot.
    if (before.has(v) && before.get(v) !== sha) die(`v${v}.json.txt no longer matches its recorded sha256 ${before.get(v)}: a frozen snapshot is never changed.`);
    return { v, sha };
  });
  const out = `// Generated by scripts/freeze-trap-set.mjs. Do not edit by hand: run \`node scripts/freeze-trap-set.mjs --index\`.
// Frozen Trap Set snapshots (B3-05, ADR 0101), bundled as text (wrangler.jsonc "rules") so they are served byte for byte.
// Each sha256 was taken from the file when it was frozen; test/benchmark-versions.test.ts fails if a file's bytes change.
${versions.map((v) => `import ${id(v)} from "./v${v}.json.txt";`).join("\n")}

export interface SnapshotEntry {
  version: string;
  sha256: string;
  text: string;
}

const text = (m: unknown) => {
  if (typeof m !== "string") throw new Error("Trap Set snapshot not bundled as text: check the wrangler.jsonc rules");
  return m;
};

export const SNAPSHOTS: SnapshotEntry[] = [
${lines.map(({ v, sha }) => `  { version: ${JSON.stringify(v)}, sha256: ${JSON.stringify(sha)}, text: text(${id(v)}) },`).join("\n")}
];
`;
  writeFileSync(join(dir, "index.ts"), out);
  console.log(`index.ts: ${versions.join(", ")}`);
}

if (process.argv.includes("--index")) {
  writeIndex();
  process.exit(0);
}

const version = arg("version") ?? die("--version is required");
const kind = arg("kind") ?? "frozen";
if (!["frozen", "reconstructed"].includes(kind)) die("--kind is frozen or reconstructed");
const file = join(dir, `v${version}.json.txt`);
if (existsSync(file)) die(`${file} exists: a frozen snapshot is never changed.`);

let def;
let commit = arg("commit");
if (arg("from-definition")) {
  if (kind !== "reconstructed" || !commit) die("--from-definition needs --kind reconstructed and --commit <sha>");
  def = JSON.parse(readFileSync(arg("from-definition"), "utf8"));
} else {
  if (kind !== "frozen") die("only a frozen snapshot is built from the current code");
  commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  const dirty = execFileSync("git", ["status", "--porcelain", "--", "apps/forge/src", "packages"], { cwd: root, encoding: "utf8" }).trim();
  if (dirty) console.warn("warning: uncommitted changes under apps/forge/src or packages; the recorded commit may not be the code that built this file");
  const tmp = join(app, "test", `zz-freeze-${process.pid}.test.ts`);
  const out = join(app, "test", `zz-freeze-${process.pid}.json`);
  writeFileSync(
    tmp,
    `import { expect, it } from "vitest";
import { trapSetDefinition } from "../src/arena/benchmark-versions";
it("freeze", async () => {
  const d = trapSetDefinition();
  expect(d.version).toBe(${JSON.stringify(version)});
  await expect(JSON.stringify(d)).toMatchFileSnapshot(${JSON.stringify(`./zz-freeze-${process.pid}.json`)});
});
`,
  );
  try {
    execFileSync("npx", ["vitest", "run", tmp, "--maxWorkers=1"], { cwd: app, stdio: "inherit", env: { ...process.env, CI: "" } });
    def = JSON.parse(readFileSync(out, "utf8"));
  } catch {
    die(`Could not build the definition for ${version} (is it the current TRAP_SET.version?)`);
  } finally {
    rmSync(tmp, { force: true });
    rmSync(out, { force: true });
  }
}
if (def.version !== version) die(`the definition is version ${def.version}, not ${version}`);

const madeOn = arg("made-on") ?? new Date().toISOString().slice(0, 10);
const short = commit.slice(0, 7);
const longDay = new Date(`${madeOn}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
const live = "https://theagentforge.io/benchmark/v1.json";
const snapshot = {
  trap_set_version: version,
  kind,
  made_on: madeOn,
  from_commit: commit,
  original_bytes: kind === "frozen",
  counts_as_of: madeOn,
  results: {
    included: false,
    reason: kind === "frozen" ? "per_model_results_are_live_and_not_part_of_the_versioned_definition" : "results_at_the_time_were_not_kept",
    live,
  },
  statement:
    kind === "frozen"
      ? `Frozen on ${longDay} from the code at commit ${short}. These bytes are fixed from then on. Counts are the Trap Set's own (traps, trap kinds, jobs, job versions) as at ${longDay}. Per-model results are not in this file: they keep growing and are live at ${live}.`
      : `Reconstructed on ${longDay} from the catalog at commit ${short}, the last commit where ${version} was the current version. Not the original bytes: ${version} was served live from code and no copy was kept. Counts are the Trap Set's own (traps, trap kinds, jobs, job versions) as rebuilt. Per-model results from that time were not kept and are not in this file; current results are live at ${live}.`,
};
writeFileSync(file, `${JSON.stringify({ snapshot, ...def }, null, 2)}\n`);
console.log(`wrote ${file}`);
writeIndex();
